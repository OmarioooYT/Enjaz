function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || (I18N.ar && I18N.ar[key]) || key;
}

function applyLanguage(lang, showNotification = false) {
  currentLang = lang === 'en' ? 'en' : 'ar';
  localStorage.setItem('enjaz_lang', currentLang);
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.title = t('pageTitle');

  const langBtn = document.getElementById('langSwitchBtn');
  if (langBtn) {
    langBtn.setAttribute('data-lang', currentLang);
    langBtn.setAttribute('aria-checked', currentLang === 'en' ? 'true' : 'false');
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });

  const syncText = document.getElementById('syncText');
  if (syncText && syncText.dataset.state) {
    syncText.textContent = t(syncText.dataset.state);
  }

  renderAuthUI();
  renderAll();
  if (typeof renderAiDrawerUI === 'function') renderAiDrawerUI();
  const tutModal = document.getElementById('tutorialModal');
  if (tutModal && !tutModal.classList.contains('hidden')) renderTutorialStep();

  if (showNotification) {
    if (!prefersReducedMotion()) {
      const workspace = document.getElementById('activeWorkspaceContent');
      const emptyState = document.getElementById('emptyProjectsState');
      const target = (workspace && !workspace.classList.contains('hidden')) ? workspace : emptyState;
      if (target) {
        clearTimeout(window._langAnimTimer);
        target.classList.remove('animate-lang-swap');
        void target.offsetWidth;
        target.classList.add('animate-lang-swap');
        window._langAnimTimer = setTimeout(() => {
          target.classList.remove('animate-lang-swap');
        }, 260);
      }
    }
    showToast(t('langSwitchedToast'));
  }
}

function toggleLanguage() {
  applyLanguage(currentLang === 'ar' ? 'en' : 'ar', true);
}

// Sync desktop & mobile search inputs (debounced workspace render)
let _searchRenderTimer = null;
function syncSearch(val) {
  searchQuery = val || '';
  const d = document.getElementById('searchInput');
  const m = document.getElementById('mobileSearchInput');
  if (d && d.value !== searchQuery) d.value = searchQuery;
  if (m && m.value !== searchQuery) m.value = searchQuery;
  clearTimeout(_searchRenderTimer);
  _searchRenderTimer = setTimeout(() => renderWorkspace(), 120);
}
